/** Sorted keys for fast prefix suggestion */
export const DICT_KEYS = Object.keys(DICT).sort();

/** Suggest dictionary words for a roman prefix (max 6) */
export interface Suggestion {
  roman: string;
  text: string;
}

export function suggestFor(tail: string, script: 'hi' | 'ur'): Suggestion[] {
  const q = tail.toLowerCase();
  if (q.length < 2) return [];
  const out: Suggestion[] = [];
  const seen = new Set<string>();
  for (const k of DICT_KEYS) {
    if (k.startsWith(q)) {
      const text = DICT[k][script === 'hi' ? 0 : 1];
      if (text && !seen.has(text)) {
        seen.add(text);
        out.push({ roman: k, text });
      }
      if (out.length >= 6) break;
    }
  }
  return out;
}
